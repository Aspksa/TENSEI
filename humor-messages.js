  throw Error('Humor catalog must contain exactly 309 distinct messages');
export function humorCategory(stage=''){
  const label=String(stage).toLowerCase();
  if(/загруз|изображ|фото|opencv|геомет|сетк|качеств/.test(label))return 'photo';
  if(/paddle|ocr|рукопис|распозна|строк|ячейк|cloud|cloud.ru/.test(label))return 'handwriting';
  return 'processing';
}
export function createHumorRotator(random=Math.random){
  const decks=new Map();
  const last=new Map();
  return function next(category='processing'){
    const type=CATEGORIES.includes(category)?category:'processing';
    let deck=decks.get(type);
    if(!deck?.length){
      const choices=HUMOR_MESSAGES.filter(item=>item.category===type);
      deck=[...choices];
      for(let i=deck.length-1;i>0;i--){
        const sample=Number(random());
        const j=Math.min(i,Math.max(0,Math.floor((Number.isFinite(sample)?sample:0)* (i+1))));
        [deck[i],deck[j]]=[deck[j],deck[i]];
      }
      const old=last.get(type);
      if(deck.length>1&&deck.at(-1)?.text===old)[deck[0],deck[deck.length-1]]=[deck[deck.length-1],deck[0]];
      decks.set(type,deck);
    }
    const item=deck.pop();
    last.set(type,item.text);
    return item.text;
  };
}
